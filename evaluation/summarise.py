"""Collect every artifacts/eval/*_metrics.json into one readable EVALUATION_SUMMARY.md (tables for the report)."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__)); OUT = os.path.join(HERE, "..", "artifacts", "eval")
L = lambda n: json.load(open(os.path.join(OUT, n))) if os.path.exists(os.path.join(OUT, n)) else None
pct = lambda v: f"{100 * v:.1f}%"
md = ["# SignBridge — evaluation summary", "", "Generated by `evaluation/summarise.py` from `artifacts/eval/*.json`.", ""]

ms = L("multisigner_metrics.json")
if ms:
    names = {"O": "original signer", "SA": "Surrey signer A", "SB": "Surrey signer B (A-F)", "AN": "ASLNow! participants (pooled)"}
    E1 = ms["E1_single_signer_model"]; E2 = ms["E2_leave_one_source_out"]["per_source"]; E3 = ms["E3_leave_one_source_out_augmented"]["per_source"]
    md += ["## Pipeline A — letter recognition on people the model never saw", "",
           "| Held-out source | Frames | E1 original model | E2 leave-one-source-out | E3 + augmentation | E3 macro-F1 |", "|---|---|---|---|---|---|"]
    for s in ["O", "SA", "SB", "AN"]:
        e1 = pct(E1[s]["best"]["accuracy"]) if s in E1 else "(training data)"
        md.append(f"| {names[s]} | {ms['sources'][s]['frames']} | {e1} | {pct(E2[s]['accuracy'])} | {pct(E3[s]['accuracy'])} | {E3[s]['macro_f1']:.3f} |")
    md += ["", f"Means: E1 {pct(ms['E1_mean_best_convention'])} · E2 {pct(ms['E2_leave_one_source_out']['mean_accuracy'])} · "
               f"E3 {pct(ms['E3_leave_one_source_out_augmented']['mean_accuracy'])} · E4 pooled random 5-fold (optimistic) {pct(ms['E4_pooled_random_5fold']['accuracy'])}", "",
           "Few-shot calibration, k = 5 per letter (original signer + Surrey A; Surrey B chose the temperature):", "",
           "| Model | Temperature | Accuracy | Frames typing the right letter |", "|---|---|---|---|"]
    E5 = ms["E5_fewshot_calibration"]
    for tname in ["shipped_temp_0.8", "revised_temp"]:
        for model in ["single_signer_model", "leave_one_source_out_model"]:
            r = E5[tname][model]["mean"]["k=5"]; r0 = E5[tname][model]["mean"]["k=0"]
            md.append(f"| {model.replace('_', ' ')} | {E5['temperatures'][tname]} | {pct(r0['accuracy'])} → {pct(r['accuracy'])} | {pct(r0['confident_correct'])} → {pct(r['confident_correct'])} |")
    md += ["", f"MediaPipe detection rate: {ms['E0_detection_rate']}; top confusions: " +
           ", ".join(f"{c['true']}→{c['pred']}" for c in ms["E3_top_confusions"][:5]), ""]

sp = L("speech_metrics.json")
if sp:
    md += ["## Pipeline B — Whisper (base) speech-to-text", "", "| Test | Utterances | Speakers | WER | Worst speaker | p50 latency |", "|---|---|---|---|---|---|"]
    for k, lab in [("S1_librispeech_test_clean", "S1 LibriSpeech test-clean"), ("S2_librispeech_test_other", "S2 LibriSpeech test-other"),
                   ("S4_call_phrases_synthetic_voices", "S4 call phrases, 8 voices")]:
        r = sp[k]; md.append(f"| {lab} | {r['n']} | {r['n_speakers']} | {pct(r['wer'])} | {pct(r['worst_speaker_wer'])} | {r['latency_p50_ms']:.0f} ms |")
    md += ["", "Noise robustness (S3, 30 utterances): " + ", ".join(f"{k}: {pct(v['wer'])}" for k, v in sp["S3_noise_robustness"].items()), ""]

tn = L("tone_metrics.json")
if tn:
    md += ["## Tone tagger", "", "| Test | Model accuracy | Model macro-F1 | VADER macro-F1 |", "|---|---|---|---|",
           f"| T1 SST-5 (5 classes, n=2210) | {pct(tn['T1_sst5']['five_class']['accuracy'])} | {tn['T1_sst5']['five_class']['macro_f1']:.3f} | – |",
           f"| T1 SST-5 collapsed to 3 classes | {pct(tn['T1_sst5']['three_class']['accuracy'])} | {tn['T1_sst5']['three_class']['macro_f1']:.3f} | {tn['T1_sst5']['vader_three_class']['macro_f1']:.3f} |",
           f"| T2 call dialogue (3 classes, n=60) | {pct(tn['T2_call_dialogue']['three_class']['accuracy'])} | {tn['T2_call_dialogue']['three_class']['macro_f1']:.3f} | {tn['T2_call_dialogue']['vader_three_class']['macro_f1']:.3f} |"]
    for lang, r in tn["T3_multilingual"].items():
        md.append(f"| T3 {lang} (n={r['n']}) | {pct(r['three_class']['accuracy'])} | {r['three_class']['macro_f1']:.3f} | {r['vader_three_class']['macro_f1']:.3f} |")
    md.append("")

sm = L("smoother_metrics.json")
if sm:
    md += ["## Sentence smoother (30 cases)", "", "| System | Exact | Acceptable | Mean WER | p50 latency |", "|---|---|---|---|---|"]
    for k, lab in [("rule_gloss_grammar", "Rules / gloss grammar"), ("llm", "Local LLM only (Qwen2.5-0.5B stand-in)"),
                   ("hybrid_v1_grammar_then_llm", "v1: grammar → LLM"), ("hybrid_v2_grammar_dictionary_then_llm", "v2: grammar → dictionary → LLM"),
                   ("hybrid_v3_v2_plus_faithfulness_guard", "v3: v2 + faithfulness guard")]:
        if k not in sm: continue
        r = sm[k]; md.append(f"| {lab} | {pct(r['exact_match_rate'])} | {pct(r['acceptable_match_rate'])} | {r['mean_wer']:.2f} | {r['latency_p50_ms']:.0f} ms |")
    if "faithfulness_guard" in sm:
        g = sm["faithfulness_guard"]
        md.append(f"\nFaithfulness guard: rejected {g['rejected']} of {g['llm_calls']} LLM sentences; invented-content rate {sm.get('invented_content_rate')}")
    md.append("")

e2e = L("e2e_metrics.json")
if e2e:
    A, B = e2e["pipeline_A_sign_to_speech"], e2e["pipeline_B_speech_to_sign"]
    md += ["## End to end", "", "| Pipeline A configuration | Accuracy | Message exact | Heard WER (capped at 100%) |", "|---|---|---|---|"]
    for k, r in A.items():
        if isinstance(r, dict) and "letter_accuracy" in r and "per_frame_accuracy" in r:
            md.append(f"| {k} | {pct(r['per_frame_accuracy'])} per frame · {pct(r['letter_accuracy'])} letters | {pct(r['message_exact_rate'])} | {pct(r['closed_loop_heard_wer_capped'])} |")
    imp = {k: r for k, r in A.items() if isinstance(r, dict) and "wrong_spoken_rate" in r}
    if imp:
        md += ["", "Improved message typing (settings chosen on validation messages):", "",
               "| Configuration | Letters | Message exact | Wrong message spoken | Asked to repeat |", "|---|---|---|---|---|"]
        if "baseline_wrong_spoken_rate" in A:
            base = A.get("multi_signer_calibrated_k5_revised_temp", {})
            md.append(f"| previous pipeline (calibrated) | {pct(base.get('letter_accuracy', 0))} | {pct(base.get('message_exact_rate', 0))} | {pct(A['baseline_wrong_spoken_rate'])} | 0.0% |")
        for k, r in imp.items():
            md.append(f"| {k} | {pct(r['letter_accuracy'])} | {pct(r['message_exact_rate'])} | {pct(r['wrong_spoken_rate'])} | {pct(r['repeat_request_rate'])} |")
    md += ["", f"Pipeline A per-stage p50 latency (ms): {A['latency_ms_p50']}", "",
           f"Pipeline B: {json.dumps({k: v for k, v in B.items()})}", ""]
open(os.path.join(OUT, "EVALUATION_SUMMARY.md"), "w").write("\n".join(md))
print("\n".join(md))
